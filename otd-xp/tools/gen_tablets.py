#!/usr/bin/env python3
"""Convert OpenTabletDriver tablet configurations (JSON) into tablets.txt for otd-xp.

usage: gen_tablets.py <OpenTabletDriver.Configurations/Configurations dir> <out tablets.txt>

Line format (pipe separated):
 name|vid|pid|report_len|parser|skip|max_x|max_y|max_pressure|width_mm|height_mm|feature_init|output_init|init_strings
 feature_init / output_init: hex byte strings separated by ';'
 init_strings: string descriptor indices separated by ','
"""
import base64, glob, json, os, sys

PARSERS = {
    "OpenTabletDriver.Plugin.Tablet.TabletReportParser": ("std", 0),
    "OpenTabletDriver.Configurations.Parsers.SkipByteTabletReportParser": ("std", 1),
    "OpenTabletDriver.Configurations.Parsers.XP_Pen.XP_PenReportParser": ("xppen", 0),
    "OpenTabletDriver.Configurations.Parsers.UCLogic.UCLogicReportParser": ("uclogic", 0),
    "OpenTabletDriver.Configurations.Parsers.UCLogic.UCLogicTiltReportParser": ("uclogic", 0),
    "OpenTabletDriver.Configurations.Parsers.Huion.GianoReportParser": ("giano", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.Intuos.IntuosReportParser": ("intuos", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.Intuos.WacomDriverIntuosReportParser": ("intuos", 1),
    "OpenTabletDriver.Configurations.Parsers.Wacom.IntuosV1.IntuosV1ReportParser": ("intuosv1", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.IntuosV1.WacomDriverIntuosV1ReportParser": ("intuosv1", 1),
    "OpenTabletDriver.Configurations.Parsers.Wacom.Bamboo.BambooReportParser": ("bamboo", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.IntuosV2.IntuosV2ReportParser": ("intuosv2", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.IntuosV2.WacomDriverIntuosV2ReportParser": ("intuosv2", 1),
    "OpenTabletDriver.Configurations.Parsers.Wacom.Intuos3.Intuos3ReportParser": ("intuos3", 0),
    "OpenTabletDriver.Configurations.Parsers.Wacom.Intuos3.WacomDriverIntuos3ReportParser": ("intuos3", 1),
}

def hexlist(reports):
    if not reports:
        return ""
    return ";".join(base64.b64decode(r).hex() for r in reports)

def main(src, dst):
    lines, supported, unsupported = [], 0, 0
    for path in sorted(glob.glob(os.path.join(src, "*", "*.json"))):
        with open(path, encoding="utf-8-sig") as f:
            d = json.load(f)
        spec = d["Specifications"]
        dig = spec["Digitizer"]
        pen = spec.get("Pen") or {}
        for ident in d["DigitizerIdentifiers"]:
            cls = ident["ReportParser"]
            parser, skip = PARSERS.get(cls, ("unsupported", 0))
            if parser == "unsupported":
                unsupported += 1
                parser = "unsupported:" + cls.rsplit(".", 1)[-1]
            else:
                supported += 1
            name = d["Name"].replace("|", "/")
            lines.append("|".join(str(x) for x in [
                name, ident["VendorID"], ident["ProductID"], ident["InputReportLength"],
                parser, skip, int(dig["MaxX"]), int(dig["MaxY"]), int(pen.get("MaxPressure") or 0),
                dig["Width"], dig["Height"],
                hexlist(ident.get("FeatureInitReport")), hexlist(ident.get("OutputInitReport")),
                ",".join(str(i) for i in (ident.get("InitializationStrings") or [])),
            ]))
    with open(dst, "w", newline="\n") as f:
        f.write("# generated by tools/gen_tablets.py from OpenTabletDriver tablet configurations (LGPL-3.0-or-later)\n")
        f.write("# name|vid|pid|report_len|parser|skip|max_x|max_y|max_pressure|width_mm|height_mm|feature_init|output_init|init_strings\n")
        f.write("\n".join(lines) + "\n")
    print("%d supported, %d unsupported identifiers" % (supported, unsupported))

if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
